def all_items():
    """拍平所有事项"""
    out = []
    for g in KB:
        for it in g["items"]:
            it2 = dict(it)
            it2["cat"] = g["cat"]
            out.append(it2)
    return out


def ok_items():
    """可办理事项"""
    return [i for i in all_items() if i["ok"]]


def blocked_items():
    """不能办理事项"""
    return [i for i in all_items() if not i["ok"]]


def flatten_for_index():
    """生成检索语料：每事项 + 平台信息 + 报价备注 + 案例"""
    docs = []
    for it in all_items():
        body = "\n".join(f"{k}：{v}" for k, v in it["fields"])
        docs.append({
            "id": f"item-{it['no']}",
            "title": f"{it['cat']} · {it['no']}. {it['name']}",
            "content": f"办理状态：{'☑ 可办理' if it['ok'] else '☐ 不能办理'}\n价格：{it['price'] or '—'}\n{body}",
            "ok": it["ok"],
            "no": it["no"],
        })
    for i, c in enumerate(CASES):
        docs.append({"id": f"case-{i}", "title": f"案例 · {c['scene']}",
                     "content": f"{c['detail']}\n价格：{c['price']}\n关键词：{'、'.join(c['tags'])}",
                     "ok": True, "no": 0})
    for p in PLATFORM:
        docs.append({"id": "plat-" + p["title"], "title": "平台 · " + p["title"],
                     "content": p["content"], "ok": True, "no": 0})
    fee = "\n".join("：".join([r[0], r[1] or "—"]) for r in FEE_TABLE[1:])
    docs.append({"id": "fee", "title": "平台 · 收费标准总表", "content": fee, "ok": True, "no": 0})
    return docs


