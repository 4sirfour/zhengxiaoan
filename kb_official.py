def lookup(keyword):
    """按关键词在官方底库中查找事项材料"""
    k = (keyword or "").strip()
    if not k:
        return None
    if k in OFFICIAL:
        return OFFICIAL[k]
    # 模糊匹配：关键词包含 key，或 key 包含关键词
    for key, val in OFFICIAL.items():
        if key in k or k in key:
            return val
    # 再按官方事项名匹配
    for key, val in OFFICIAL.items():
        if val["name"] and k in val["name"]:
            return val
    return None


