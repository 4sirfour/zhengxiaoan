def is_hague_member(name):
    """判断国家/地区是否属海牙公约适用范围。返回 (是否成员, 规范化名称)。"""
    if not name:
        return False, ""
    n = (name or "").strip()
    if n in HAGUE_REGIONS:
        return True, HAGUE_REGIONS[n]
    n = HAGUE_ALIAS.get(n, n)
    if n in HAGUE_MEMBERS_CN:
        return True, n
    # 模糊兜底：简称包含关系（如「美利坚」→「美国」）
    for m in HAGUE_MEMBERS_CN:
        if len(m) >= 2 and (m in n or n in m):
            return True, m
    return False, n


