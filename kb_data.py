def all_items():
    """拍平所有事项"""
    out = []
    for g in KB:
        for it in g["items"]:
            it2 = dict(it)
            it2["cat"] = g["cat"]
            out.append(it2)
    return out


def ext_items():
    return [i for i in all_items() if i["mark"] == "ext"]


def int_items():
    return [i for i in all_items() if i["mark"] == "int"]


def flatten_for_index():
    """生成检索语料：每事项 + 平台信息 + 报价备注"""
